"""
Render the sparsity experiment of Fig. 8 for every hemisphere geometry.

For each geometry XML in --input-dir (generated by create_icospheres_densities.py)
this writes, under --runs-dir/<geometry name>/:
    ours10/        our method at --spp samples per pixel
    pt10/          path tracing at the same spp
    pt_equaltime/  path tracing with the spp scaled to match the render time of ours10
    ptref/         path-traced reference at --ref-spp
each with render.exr and stdout.log, which is the layout read by
analyze_hemisphere_runs.py.

Run from the repository root inside the container (the scenes reference
their meshes relative to it), e.g.:
    python3 scenes/9_rebuttal_sphere/create_icospheres_densities.py -o scenes/9_rebuttal_sphere/hemispheres_log
    python3 scenes/9_rebuttal_sphere/run_hemispheres.py -i scenes/9_rebuttal_sphere/hemispheres_log
    python3 scenes/9_rebuttal_sphere/analyze_hemisphere_runs.py -i scenes/9_rebuttal_sphere/runs
"""
import argparse
import os
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent


def render(scene, geometry, spp, out_dir, extra=()):
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = ["mitsuba", "-z", str(scene), f"-Dgeometry={geometry}", f"-Dspp={spp}",
           "-o", str(out_dir / "render.exr"), *extra]
    p = subprocess.run(cmd, capture_output=True, text=True)
    (out_dir / "stdout.log").write_text(p.stdout + p.stderr)
    if p.returncode != 0:
        raise RuntimeError(f"mitsuba failed for {out_dir}:\n{p.stdout[-2000:]}{p.stderr[-2000:]}")
    m = re.search(r"Render time: ([0-9.]+)(ms|s|m|h)", p.stdout)
    scale = {"ms": 1e-3, "s": 1.0, "m": 60.0, "h": 3600.0}
    return float(m.group(1)) * scale[m.group(2)] if m else None


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("-i", "--input-dir", default=str(HERE / "hemispheres_log"),
                   help="Directory with the hemisphere geometry XML files.")
    p.add_argument("-r", "--runs-dir", default=str(HERE / "runs"), help="Output directory.")
    p.add_argument("--ours-scene", default=str(HERE / "1_wildcard_icosphere_xs.xml"))
    p.add_argument("--pt-scene", default=str(HERE / "1_wildcard_icosphere_path_xs.xml"))
    p.add_argument("--spp", type=int, default=10, help="Samples per pixel of ours and of PT at equal spp.")
    p.add_argument("--ref-spp", type=int, default=4096, help="Samples per pixel of the PT reference.")
    p.add_argument("--resume", action="store_true", help="Skip renders whose output already exists.")
    args = p.parse_args()

    input_dir = Path(args.input_dir)
    for xml in sorted(input_dir.glob("*.xml")):
        # Very sparse, coarse hemispheres can end up without any triangle
        if re.search(r"_n0_", xml.stem):
            print(f"{xml.stem}: no triangles, skipped")
            continue
        # The scenes include the geometry relative to their own folder
        geometry = os.path.relpath(xml, HERE)
        run_dir = Path(args.runs_dir) / xml.stem
        print(f"{xml.stem}:")

        def todo(name):
            return not (args.resume and (run_dir / name / "render.exr").exists())

        t_ours = render(args.ours_scene, geometry, args.spp, run_dir / "ours10") if todo("ours10") else None
        t_pt = render(args.pt_scene, geometry, args.spp, run_dir / "pt10") if todo("pt10") else None
        if todo("pt_equaltime") and t_ours and t_pt:
            spp_eq = max(1, round(args.spp * t_ours / t_pt))
            render(args.pt_scene, geometry, spp_eq, run_dir / "pt_equaltime")
            print(f"  ours {t_ours:.3f} s, PT {t_pt:.3f} s -> PT equal time at {spp_eq} spp")
        if todo("ptref"):
            render(args.pt_scene, geometry, args.ref_spp, run_dir / "ptref")


if __name__ == "__main__":
    main()
